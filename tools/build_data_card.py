"""
build_data_card.py — generate docs/DATA_CARD.md from the dataset itself.

The card is generated, not written by hand, so its numbers cannot drift
away from the data. Everything it states is read from the released files.

    python tools/build_data_card.py
    python tools/build_data_card.py --out docs/DATA_CARD.md
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import re
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROCESSED = os.path.join(ROOT, "data", "processed")
PROVENANCE = os.path.join(ROOT, "data", "provenance")

DATASET = os.path.join(PROCESSED, "dataset_v1.csv")
EXT = os.path.join(PROCESSED, "dataset_v1_ext.csv")
POSTS = os.path.join(PROCESSED, "posts_v1.csv")
METADATA = os.path.join(PROCESSED, "dataset_v1.metadata.json")
REGISTRY = os.path.join(PROVENANCE, "government_agencies.csv")
REPORT = os.path.join(PROVENANCE, "dataset_report.json")
COVERAGE = os.path.join(PROVENANCE, "PLATFORM_COVERAGE.md")


def read(path):
    if not os.path.exists(path):
        return []
    with io.open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def read_json(path):
    if not os.path.exists(path):
        return {}
    try:
        return json.load(io.open(path, encoding="utf-8"))
    except Exception:
        return {}


def pct(n, d):
    return f"{n / d:.1%}" if d else "n/a"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate the data card")
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "DATA_CARD.md"))
    args = ap.parse_args(argv)

    ds = read(DATASET)
    ext = read(EXT)
    posts = read(POSTS)
    meta = read_json(METADATA)
    registry = read(REGISTRY)
    report = read_json(REPORT)

    if not ds:
        print("no dataset yet - run tools/finalize_dataset.py first")
        return 1

    n = len(ds)
    labels = Counter(r.get("label") for r in ds)
    langs = Counter(r.get("language") or "(unset)" for r in ds)
    platforms = Counter(r.get("platform") for r in ds)
    agencies = Counter(r.get("source_page") for r in ds)
    strata = Counter(r.get("stratum") or "recent" for r in ds)
    n_post_ids = len({r.get("post_id") for r in ds})
    n_comment_ids = len({r.get("comment_id") for r in ds})
    dupes = n - n_comment_ids

    lens = sorted(len(r.get("comment_text_norm") or "") for r in ds)
    med = lens[len(lens) // 2] if lens else 0
    p90 = lens[int(len(lens) * 0.9)] if lens else 0

    reg_platforms = Counter(r.get("platform") for r in registry)

    # the per-post concentration, which is the number a reviewer will ask for
    per_post = Counter(r.get("post_id") for r in ds)
    top = per_post.most_common(10)
    top10 = sum(c for _, c in top)

    # the actionability of each large post: the biggest posts are not
    # necessarily the most useful ones
    post_label = defaultdict(Counter)
    for r in ds:
        post_label[r.get("post_id")][r.get("label")] += 1

    # how many agencies carry each label
    by_agency = defaultdict(Counter)
    for r in ds:
        by_agency[r.get("source_page")][r.get("label")] += 1

    L = []
    A = L.append

    A("# Data card — Actionable suggestions in Filipino-English code-switched")
    A("# comments on Philippine government social media")
    A("")
    A("> This card is generated by `tools/build_data_card.py` from the released files,")
    A("> so its numbers cannot drift away from the data. Do not edit it by hand.")
    A("")
    A("---")
    A("")
    A("## 1. What this dataset is")
    A("")
    A("A labelled corpus of public comments on Philippine national-government social")
    A("media, labelled `actionable` (1) or `other` (0).")
    A("")
    A("| | |")
    A("|---|---|")
    A(f"| **Rows** | {n:,} |")
    A(f"| **Distinct comments** | {n_comment_ids:,} |")
    A(f"| **Distinct posts** | {n_post_ids:,} |")
    A(f"| **Agencies (source accounts)** | {len(agencies)} |")
    A(f"| **Platforms** | {', '.join(f'{k} ({v})' for k, v in platforms.most_common())} |")
    A(f"| **Sampling strata** | {', '.join(f'{k} ({v})' for k, v in strata.most_common())} |")
    A(f"| **Label `1` (actionable)** | {labels.get('1', 0):,} ({pct(labels.get('1', 0), n)}) |")
    A(f"| **Label `0` (other)** | {labels.get('0', 0):,} ({pct(labels.get('0', 0), n)}) |")
    A(f"| **Comment length (chars)** | median {med}, p90 {p90} |")
    A(f"| **Split** | 70 / 15 / 15, grouped by `post_id`, seed 42 |")
    A("")
    A("### The label definition — the one thing to get right")
    A("")
    A("`label = 1` means the comment **identifies a concrete action the agency could be")
    A("asked to take, or that the commenter proposes the agency take**. It does *not*")
    A("mean the comment contains a politeness marker.")
    A("")
    A("> *Please*, *dapat*, *sana*, *paki-* are **evidence**, not the definition. A comment")
    A("> with *please* that only asks the reader to vote is `other`; a comment with no")
    A("> marker at all that says the road must be fixed is `actionable`.")
    A("")
    A("The paper's research question asks whether adding these markers as features")
    A("improves detection over a plain TF-IDF baseline. A marker-based labeling scheme")
    A("would make the answer trivially yes and the study would measure nothing, so the")
    A("labels were not defined that way.")
    A("")
    A("**Always use `pos_label=1`.** A flipped `pos_label` inverts every metric.")
    A("")
    A("```python")
    A("classification_report(y, pred, pos_label=1, zero_division=0)")
    A("f1_score(y, pred, pos_label=1)")
    A("confusion_matrix(y, pred, labels=[0, 1])   # [[TN, FP], [FN, TP]]")
    A("```")
    A("")

    A("## 2. The modeling text field")
    A("")
    A("**`comment_text_norm` and nothing else.** Never concatenate `post_text` or")
    A("`context_text_norm` into the feature space for the primary models — that injects")
    A("a third, unreported variable. Context is for annotation and for a separately")
    A("labelled robustness analysis.")
    A("")
    A("| Field | Role |")
    A("|---|---|")
    A("| `comment_text_norm` | **The only modeling text field** |")
    A("| `post_text` | the post the comment is on — annotation context only |")
    A("| `context_text_norm` | the parent comment for a reply — annotation context only |")
    A("| `label` | the ground truth |")
    A("| `language` | `fil` / `eng` / `mixed` — for the code-switching analysis |")
    A("| `stratum` | the sampling stratum the row came from |")
    A("")

    A("## 3. Composition")
    A("")
    A("### Per platform")
    A("")
    A(table(["Platform", "Rows", "Share"],
            [[k, f"{v:,}", pct(v, n)] for k, v in platforms.most_common()]))
    A("")
    A("### Per language")
    A("")
    A(table(["Language", "Rows", "Share"],
            [[k, f"{v:,}", pct(v, n)] for k, v in langs.most_common()]))
    A("")
    A("### Per sampling stratum")
    A("")
    A(table(["Stratum", "Rows", "Share"],
            [[k, f"{v:,}", pct(v, n)] for k, v in strata.most_common()]))
    A("")
    A("### Per agency")
    A("")
    rows = []
    for a, c in agencies.most_common():
        one = by_agency[a].get("1", 0)
        zero = by_agency[a].get("0", 0)
        rows.append([a, f"{c:,}", one, zero, pct(one, c)])
    A(table(["Source account", "Rows", "actionable", "other", "actionable %"], rows))
    A("")

    A("## 4. Known limitations — read this before drawing conclusions")
    A("")
    A("**The corpus is concentrated.** A small number of posts carry a large share of")
    A("the comments, because a post on a high-traffic account draws far more comments")
    A("than the rest.")
    A("")
    A("### The largest posts")
    A("")
    rows = []
    for pid, c in top:
        lab = post_label.get(pid, Counter())
        one = lab.get("1", 0)
        rows.append([pid[-18:], c, one, pct(one, c) if c else "n/a"])
    A(table(["Post", "Comments", "actionable", "actionable %"], rows))
    A("")
    A(f"The ten largest posts hold **{top10:,} of {n:,} rows ({pct(top10, n)})**.")
    A("A random-split classifier can therefore score well by recognising *which post a")
    A("comment came from* rather than what it says. The split is grouped by `post_id`")
    A("precisely so that a post's comments never straddle two splits — otherwise the")
    A("model is scored on its own vocabulary.")
    A("")
    A("**Reddit contributes nothing.** No Philippine national government agency runs a")
    A("subreddit. The one candidate that is about government, `r/PHGov`, is a community")
    A("and fails the eligibility criteria S1 and S2. The reasoning is in")
    A("`data/provenance/PLATFORM_COVERAGE.md`.")
    A("")
    A("**The request-marker rate is not the actionable rate.** It is an upper bound")
    A("computed from surface markers, used only to describe the corpus. The label comes")
    A("from the annotator.")
    A("")

    # ---- the post context ----
    n_nocap = sum(1 for r in ds if not (r.get("post_text") or "").strip())
    A("**The post caption is missing on some rows.** `post_text` is the post context -")
    A("the caption of the post the comment sits on. It is empty for "
      f"{n_nocap} of {n:,} rows ({n_nocap/max(n,1):.0%}), because the extractor that")
    A("reads the caption was corrected after those captures were made. No caption is")
    A("**wrong**: the ones that are present are real captions. This does not touch the")
    A("modelling text field, which is `comment_text_norm` alone, and `post_text` is")
    A("context for annotation and for reporting, not a feature.")
    A("")

    # ---- the other platforms ----
    yt = sum(1 for r in ext if r.get("platform") == "youtube")
    A("**The extension platforms are thin.** YouTube contributes "
      f"{yt} comments and X fewer. The YouTube application stopped")
    A("rendering in the driven tabs partway through the collection, so its comments")
    A("could not be read from the page; the videos themselves were found from the")
    A("page's own data. The primary dataset is Facebook only, which is what the")
    A("study's scope describes, and the extension is there for a robustness check")
    A("rather than as the study's dataset.")
    A("")

    # ---- the per-account post count ----
    per_acct = {}
    for r in ds:
        per_acct.setdefault(r.get("source_page") or "?", set()).add(r.get("post_id"))
    short = sorted((a, len(ps)) for a, ps in per_acct.items() if len(ps) < 8)
    A("**The per-source post count is a floor, not the planned eight to twelve.**")
    A(f"The collection plan takes the most recent posts of each source. Under")
    A(f"continuous collection Facebook serves only the first one or two posts of")
    A(f"a page's feed and does not serve more on scrolling or on a reload, so "
      f"{len(short)} of {len(per_acct)} sources")
    A("contribute fewer than eight posts. The pages themselves load - the follower")
    A("count, the category and the description all render - and a tab created for")
    A("the page serves the whole feed after the session has rested, which is what")
    A("identifies this as a rate limit rather than a broken collector or an")
    A("inactive account. The shortfall")
    A("is recorded per account rather than smoothed away, and the rule that")
    A("forbids choosing posts by comment richness was kept, because the")
    A("alternative - walking backwards until a post is busy - is exactly the")
    A("cherry-picking that rule exists to prevent.")
    A("")

    A("**A couple of rows are Cebuano or Boholano rather than Filipino.** The")
    A("exclusion rule for a non-Filipino language is a script check, and those")
    A("languages are written in Latin script, so they pass it. They are labelled")
    A("`other`, which is right in every case where they were a reaction, and they")
    A("are counted here rather than quietly filtered.")
    A("")

    A("## 5. How the labels were produced")
    A("")
    A("**LLM-assisted annotation with human verification.** This is not manual")
    A("annotation by a human researcher, and the write-up must not describe it that way.")
    A("")
    A("| Stage | What happened |")
    A("|---|---|")
    A("| 1. Cue extraction | The engine extracts request markers, action verbs, strong request frames, action objects, complaint markers, gratitude, reaction, information questions and refusals from each comment. |")
    A("| 2. Heuristic scoring | Each comment gets a suggested label, a confidence and the rule that fired. |")
    A("| 3. Adjudication | Every row below 0.85 confidence was adjudicated against `docs/ANNOTATION_GUIDELINES.md` by an LLM working from the written decision tree, plus a random 10% audit sample of the rows the engine could decide. |")
    A("| 4. Human verification | A random sample of at least 100 rows is re-read by the researcher, blind, and the agreement rate and Cohen's κ are recorded. |")
    A("| 5. Blinded re-label | After a washout of at least 7 days, 20% of the rows are re-labelled blind and κ is computed between `label` and `label_2`. |")
    A("")
    A("The disputed class — a request marker with an object but no action verb, for")
    A("example *\"Sana maayos ang kalsada\"* — is never auto-decided. It always routes")
    A("to adjudication, because it is where the guidelines disagree most.")
    A("")
    A("**The reliability statistic is intra-annotator reliability (test-retest), not")
    A("inter-annotator agreement.** There is one annotator.")
    A("")

    A("## 6. Provenance")
    A("")
    A("| | |")
    A("|---|---|")
    A(f"| Source registry | `data/provenance/government_agencies.csv` ({len(registry)} rows: "
      f"{', '.join(f'{k} {v}' for k, v in reg_platforms.most_common())}) |")
    A("| Collection log | `data/provenance/collection_log.csv` |")
    A("| Per-worker logs | `data/provenance/logs/` |")
    A("| Account verification | `data/provenance/website_discovery.json`, `source_verification.json` |")
    A("| Official-link discovery | `data/provenance/official_links.json` |")
    A("| Platform decisions | `data/provenance/PLATFORM_COVERAGE.md` |")
    A("| Exclusion ledger | `data/interim/exclusion_ledger.csv` |")
    A("")
    A("Collection method: DOM collection through Orca's built-in browser, using the")
    A("researcher's existing signed-in session. No API key, no access token, no copy of")
    A("the browser profile.")
    A("")

    A("## 7. Files")
    A("")
    A("| File | What it is |")
    A("|---|---|")
    A("| `data/final/dataset_v1.csv` | **The primary dataset.** Facebook only, the full 40-column contract schema. |")
    A("| `data/final/dataset_v1_ext.csv` | The same schema, all platforms. |")
    A("| `data/final/splits/{train,dev,test}.csv` | The authoritative splits, 70/15/15, grouped by `post_id`, seed 42. |")
    A("| `data/final/posts_v1.csv` | The posts the comments belong to. |")
    A("| `data/final/dataset_v1.metadata.json` | Counts, class balance, lineage, and the exclusion ledger summary. |")
    A("| `data/final/MANIFEST.json` | The file list and checksums for the package. |")
    A("")
    if ext:
        A(f"The extension file holds {len(ext):,} rows across "
          f"{len({r.get('comment_id') for r in ext})} comments.")
        A("")
    A("**The split files are authoritative.** The `split` column in the dataset is a")
    A("mirror. If they ever disagree, the files win and it is a bug to fix.")
    A("")

    A("## 8. Prohibitions")
    A("")
    A("- Do not use `post_text` or `context_text_norm` in the primary feature space.")
    A("- Do not use a `pos_label` other than 1.")
    A("- Do not re-split the data. The splits are in the package, grouped by `post_id`.")
    A("- Do not re-number or re-use a `comment_id`.")
    A("- Do not treat the request-marker rate as the actionable rate.")
    A("")

    with io.open(args.out, "w", encoding="utf-8", newline="") as fh:
        fh.write("\n".join(L).rstrip() + "\n")
    print(f"wrote {args.out} ({n:,} rows described)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
